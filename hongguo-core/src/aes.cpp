constexpr uint8_t kRcon[11] = {0x00, 0x01, 0x02, 0x04, 0x08,
                               0x10, 0x20, 0x40, 0x80, 0x1b, 0x36};

// GF(2^8) 乘法，模 x^8 + x^4 + x^3 + x + 1
uint8_t gmul(uint8_t a, uint8_t b) {
  uint8_t result = 0;
  while (b != 0) {
    if (b & 1) result = static_cast<uint8_t>(result ^ a);
    const bool high = (a & 0x80) != 0;
    a = static_cast<uint8_t>(a << 1);
    if (high) a = static_cast<uint8_t>(a ^ 0x1b);
    b = static_cast<uint8_t>(b >> 1);
  }
  return result;
}

// 11 组轮密钥，每组 16 字节：roundKeys[r*16 + c]
using RoundKeys = uint8_t[176];

void expandKey(const uint8_t* key, RoundKeys out) {
  for (int i = 0; i < 16; ++i) out[i] = key[i];
  for (int word = 4; word < 44; ++word) {
    uint8_t temp[4];
    for (int i = 0; i < 4; ++i) temp[i] = out[(word - 1) * 4 + i];
    if (word % 4 == 0) {
      // RotWord + SubWord + Rcon
      const uint8_t first = temp[0];
      temp[0] = static_cast<uint8_t>(kSbox[temp[1]] ^ kRcon[word / 4]);
      temp[1] = kSbox[temp[2]];
      temp[2] = kSbox[temp[3]];
      temp[3] = kSbox[first];
    }
    for (int i = 0; i < 4; ++i) {
      out[word * 4 + i] =
          static_cast<uint8_t>(out[(word - 4) * 4 + i] ^ temp[i]);
    }
  }
}

void addRoundKey(uint8_t state[16], const RoundKeys keys, int round) {
  for (int i = 0; i < 16; ++i) state[i] ^= keys[round * 16 + i];
}

// AES 状态按列主序摆放：state[r + 4c] 对应文档中的 s[r][c]。
void shiftRows(uint8_t s[16]) {
  uint8_t t[16];
  for (int r = 0; r < 4; ++r) {
    for (int c = 0; c < 4; ++c) t[r + 4 * c] = s[r + 4 * ((c + r) % 4)];
  }
  for (int i = 0; i < 16; ++i) s[i] = t[i];
}

void invShiftRows(uint8_t s[16]) {
  uint8_t t[16];
  for (int r = 0; r < 4; ++r) {
    for (int c = 0; c < 4; ++c) t[r + 4 * c] = s[r + 4 * ((c - r + 4) % 4)];
  }
  for (int i = 0; i < 16; ++i) s[i] = t[i];
}

void mixColumns(uint8_t s[16]) {
  for (int c = 0; c < 4; ++c) {
    uint8_t* col = s + 4 * c;
    const uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
    col[0] = static_cast<uint8_t>(gmul(a0, 2) ^ gmul(a1, 3) ^ a2 ^ a3);
    col[1] = static_cast<uint8_t>(a0 ^ gmul(a1, 2) ^ gmul(a2, 3) ^ a3);
    col[2] = static_cast<uint8_t>(a0 ^ a1 ^ gmul(a2, 2) ^ gmul(a3, 3));
    col[3] = static_cast<uint8_t>(gmul(a0, 3) ^ a1 ^ a2 ^ gmul(a3, 2));
  }
}

void invMixColumns(uint8_t s[16]) {
  for (int c = 0; c < 4; ++c) {
    uint8_t* col = s + 4 * c;
    const uint8_t a0 = col[0], a1 = col[1], a2 = col[2], a3 = col[3];
    col[0] = static_cast<uint8_t>(gmul(a0, 14) ^ gmul(a1, 11) ^ gmul(a2, 13) ^
                                  gmul(a3, 9));
    col[1] = static_cast<uint8_t>(gmul(a0, 9) ^ gmul(a1, 14) ^ gmul(a2, 11) ^
                                  gmul(a3, 13));
    col[2] = static_cast<uint8_t>(gmul(a0, 13) ^ gmul(a1, 9) ^ gmul(a2, 14) ^
                                  gmul(a3, 11));
    col[3] = static_cast<uint8_t>(gmul(a0, 11) ^ gmul(a1, 13) ^ gmul(a2, 9) ^
                                  gmul(a3, 14));
  }
}

void encryptBlock(const RoundKeys keys, const uint8_t in[16], uint8_t out[16]) {
  uint8_t s[16];
  for (int i = 0; i < 16; ++i) s[i] = in[i];
  addRoundKey(s, keys, 0);
  for (int round = 1; round <= 9; ++round) {
    for (int i = 0; i < 16; ++i) s[i] = kSbox[s[i]];
    shiftRows(s);
    mixColumns(s);
    addRoundKey(s, keys, round);
  }
  for (int i = 0; i < 16; ++i) s[i] = kSbox[s[i]];
  shiftRows(s);
  addRoundKey(s, keys, 10);
  for (int i = 0; i < 16; ++i) out[i] = s[i];
}

void decryptBlock(const RoundKeys keys, const uint8_t in[16], uint8_t out[16]) {
  uint8_t s[16];
  for (int i = 0; i < 16; ++i) s[i] = in[i];
  addRoundKey(s, keys, 10);
  for (int round = 9; round >= 1; --round) {
    invShiftRows(s);
    for (int i = 0; i < 16; ++i) s[i] = kInvSbox[s[i]];
    addRoundKey(s, keys, round);
    invMixColumns(s);
  }
  invShiftRows(s);
  for (int i = 0; i < 16; ++i) s[i] = kInvSbox[s[i]];
  addRoundKey(s, keys, 0);
  for (int i = 0; i < 16; ++i) out[i] = s[i];
}

void requireKey(const Bytes& key) {
  if (key.size() != 16) {
    throw std::invalid_argument("AES-128 需要 16 字节密钥，实得 " +
                                std::to_string(key.size()));
  }
}

