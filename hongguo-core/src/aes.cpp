Bytes aes128CbcDecrypt(const Bytes& key, const Bytes& iv, const Bytes& data) {
  requireKey(key);
  if (iv.size() != 16) throw std::invalid_argument("AES-CBC 需要 16 字节 IV");
  if (data.size() % 16 != 0) {
    throw std::invalid_argument("AES-CBC 密文长度必须是 16 的整数倍");
  }

  RoundKeys keys;
  expandKey(key.data(), keys);

  Bytes out(data.size());
  uint8_t previous[16];
  for (int i = 0; i < 16; ++i) previous[i] = iv[i];

  for (size_t at = 0; at < data.size(); at += 16) {
    uint8_t block[16];
    decryptBlock(keys, data.data() + at, block);
    for (int i = 0; i < 16; ++i) {
      out[at + static_cast<size_t>(i)] =
          static_cast<uint8_t>(block[i] ^ previous[i]);
      previous[i] = data[at + static_cast<size_t>(i)];
    }
  }
  return out;
}

Bytes aes128Ctr(const Bytes& key, const Bytes& iv, const Bytes& data) {
  requireKey(key);
  if (iv.size() != 16) throw std::invalid_argument("AES-CTR 需要 16 字节 IV");

  RoundKeys keys;
  expandKey(key.data(), keys);

  Bytes out(data.size());
  uint8_t counter[16];
  for (int i = 0; i < 16; ++i) counter[i] = iv[i];

  for (size_t at = 0; at < data.size(); at += 16) {
    uint8_t stream[16];
    encryptBlock(keys, counter, stream);
    const size_t remaining = data.size() - at;
    const size_t take = remaining < 16 ? remaining : 16;
    for (size_t i = 0; i < take; ++i) {
      out[at + i] = static_cast<uint8_t>(data[at + i] ^ stream[i]);
    }
    // 整个 128 位块按大端加一
    for (int i = 15; i >= 0; --i) {
      if (++counter[i] != 0) break;
    }
  }
  return out;
}

